// ternary operator

let age:number =16;

let result1:string = (age>=18)?"Eligible":"Not Eligible";

console.log(result1);

let result2:number = (age>=18)? 10:11;

console.log(result2);

let result3:boolean = (age>=18)? true:false;

console.log(result3);

let result4:any = (age>=18)? "Eligible":false;

console.log(result4);


